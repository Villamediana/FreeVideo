    // ------------------------------------------------------------------------ links

    /** A YouTube video / channel / playlist link inside [text]; null when there is none. */
    suspend fun resolve(text: String): TubeLink? {
        val url = YouTubeLinks.extractUrl(text) ?: text.trim().takeIf { it.startsWith("http") } ?: return null
        return runCatching {
            io("link") {
                when (service.getLinkTypeByUrl(url)) {
                    StreamingService.LinkType.STREAM -> TubeLink.Video(service.streamLHFactory.fromUrl(url).id, startOf(url))
                    StreamingService.LinkType.CHANNEL -> TubeLink.Channel(service.channelLHFactory.fromUrl(url).url)
                    StreamingService.LinkType.PLAYLIST -> TubeLink.Playlist(service.playlistLHFactory.fromUrl(url).url)
                    else -> null
                }
            }
        }.getOrNull()
    }

    // ------------------------------------------------------------------------ import

    /**
     * Subscriptions from a Google Takeout export: the subscriptions.csv, the whole .zip, or the old
     * JSON. Returns (channel url, name) pairs.
     */
    suspend fun readSubscriptions(input: java.io.InputStream, fileName: String?): List<Pair<String, String>> = io("import") {
        val extractor = org.schabi.newpipe.extractor.services.youtube.extractors.YoutubeSubscriptionExtractor(service)
        val name = fileName.orEmpty().lowercase()
        val items = when {
            name.endsWith(".zip") -> extractor.fromZipInputStream(input)
            name.endsWith(".json") -> extractor.fromJsonInputStream(input)
            else -> extractor.fromCsvInputStream(input)
        }
        items.mapNotNull { item -> item.url?.takeIf { it.isNotBlank() }?.let { it to item.name.orEmpty() } }
    }

    // ------------------------------------------------------------------------ mapping

    private fun videoOf(item: StreamInfoItem): VideoItem? {
        val id = idOf(item.url) ?: return null
        val name = item.name?.trim().orEmpty()
        if (name.isEmpty() || name == "[Private video]" || name == "[Deleted video]") return null
        val type = item.streamType
        val live = type == StreamType.LIVE_STREAM || type == StreamType.AUDIO_LIVE_STREAM
        return VideoItem(
            id = id,
            title = name,
            channelName = item.uploaderName?.trim().orEmpty(),
            channelUrl = item.uploaderUrl?.ifBlank { null },
            channelAvatar = avatar(item.uploaderAvatars),
            thumbnailUrl = videoThumb(id, item.thumbnails),
            durationMs = item.duration.takeIf { it > 0 }?.times(1000) ?: 0,
            views = item.viewCount,
            uploadedAt = runCatching { item.uploadDate?.instant?.toEpochMilli() }.getOrNull(),
            // RSS entries carry a machine date ("2026-11-18T14:30:12+00:00"): not words to show.
            uploadedText = item.textualUploadDate?.ifBlank { null }?.takeUnless { it.length >= 10 && it[4] == '-' && it[0].isDigit() },
            live = live,
            short = runCatching { item.isShortFormContent }.getOrDefault(false) || item.url.contains("/shorts/"),
            verified = runCatching { item.isUploaderVerified }.getOrDefault(false),
        )
    }

    private fun channelOf(item: ChannelInfoItem): ChannelItem? {
        val url = item.url?.ifBlank { null } ?: return null
        return ChannelItem(
            url = url,
            name = item.name?.trim().orEmpty().ifEmpty { return null },
            avatarUrl = avatar(item.thumbnails),
            subscribers = item.subscriberCount,
            videos = item.streamCount,
            description = item.description?.trim()?.ifEmpty { null },
            verified = runCatching { item.isVerified }.getOrDefault(false),
        )
    }

    private fun playlistOf(item: PlaylistInfoItem): PlaylistItem? {
        val url = item.url?.ifBlank { null } ?: return null
        return PlaylistItem(
            url = url,
            name = item.name?.trim().orEmpty().ifEmpty { return null },
            uploader = item.uploaderName?.ifBlank { null },
            thumbnailUrl = Thumbnails.best(item.thumbnails.map { Thumbnails.Thumb(it.url, it.width, it.height) }, 720),
            count = item.streamCount,
        )
    }

    internal companion object {
        /** How long a video's extraction is reused (the watch page and the player share it). */
        const val INFO_TTL_MS = 20 * 60_000L

        fun watchUrl(id: String) = "https://www.youtube.com/watch?v=$id"

        fun idOf(url: String?): String? {
            if (url.isNullOrBlank()) return null
            return runCatching { YoutubeStreamLinkHandlerFactory.getInstance().getId(url) }.getOrNull()?.takeIf { it.length == 11 }
        }

        /** A sharp 16:9 frame: YouTube's own HD crop when listed, else the 480p frame (cropped to 16:9 on screen). */
        fun videoThumb(id: String, images: List<Image>): String {
            val hd = images.filter { it.url.contains("hq720") || it.url.contains("maxresdefault") }
            if (hd.isNotEmpty()) {
                Thumbnails.best(hd.map { Thumbnails.Thumb(it.url, it.width, it.height) }, 720)?.let { return it }
            }
            return "https://i.ytimg.com/vi/$id/hqdefault.jpg"
        }

        fun avatar(images: List<Image>?): String? =
            images?.takeIf { it.isNotEmpty() }?.let { list -> Thumbnails.best(list.map { Thumbnails.Thumb(it.url, it.width, it.height) }, 176) }

        fun textOf(d: Description?): String {
            val content = d?.content ?: return ""
            return if (d.type == Description.HTML) AutoGeneratedDescription.htmlToText(content).trim() else content.trim()
        }

        /** `t=90`, `t=1m30s`, `start=90` of a shared link, in ms. */
        fun startOf(url: String): Long {
            val u = url.toHttpUrlOrNull() ?: return 0
            val t = u.queryParameter("t") ?: u.queryParameter("start") ?: return 0
            t.toLongOrNull()?.let { return it * 1000 }
            val m = Regex("^(?:(\\d+)h)?(?:(\\d+)m)?(?:(\\d+)s?)?$").matchEntire(t) ?: return 0
            val (h, min, s) = m.destructured
            return ((h.toLongOrNull() ?: 0) * 3600 + (min.toLongOrNull() ?: 0) * 60 + (s.toLongOrNull() ?: 0)) * 1000
        }
    }
