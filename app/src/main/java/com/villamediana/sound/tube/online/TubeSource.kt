/**
 * YouTube (the videos, not YouTube Music) through NewPipeExtractor — the same library FreeSong uses.
 * Everything blocks on the network inside [Dispatchers.IO] and fails as [OnlineException].
 *
 * The watch page and the player read the same [StreamInfo]: it is kept a few minutes, so opening a
 * video extracts it once for both.
 */
class TubeSource(private val http: OkHttpClient) {

    private val service: YoutubeService get() = ServiceList.YouTube

    private suspend fun <T> io(what: String, block: () -> T): T = withContext(Dispatchers.IO) {
        NewPipeHttp.init(http)
        onlineCall(what, block)
    }

    // ------------------------------------------------------------------------ search

    private class SearchCursor(val handler: SearchQueryHandler, val page: Page, val seen: Set<String>)

    suspend fun search(query: String, kind: SearchKind = SearchKind.ALL): TubePage<SearchResult> {
        val q = query.trim()
        if (q.isEmpty()) return TubePage(emptyList())
        return io("search") {
            val handler = service.searchQHFactory.fromQuery(q, listOf(filterOf(kind)), "")
            val extractor = service.getSearchExtractor(handler)
            extractor.fetchPage()
            val first = extractor.initialPage
            searchPage(handler, first.items, first.nextPage, emptySet())
        }
    }

    suspend fun moreSearch(page: TubePage<SearchResult>): TubePage<SearchResult> {
        val cursor = page.cursor as? SearchCursor ?: return TubePage(emptyList())
        return io("search more") {
            val more = SearchInfo.getMoreItems(service, cursor.handler, cursor.page)
            searchPage(cursor.handler, more.items, more.nextPage, cursor.seen)
        }
    }

    private fun searchPage(handler: SearchQueryHandler, items: List<InfoItem>, next: Page?, seen: Set<String>): TubePage<SearchResult> {
        val keys = seen.toMutableSet()
        val out = items.mapNotNull { toResult(it) }.filter { keys.add(it.key) }
        val nextPage = next?.takeIf { it.url != null || it.body != null }
        return TubePage(out, nextPage?.let { SearchCursor(handler, it, keys) })
    }

    private fun toResult(item: InfoItem): SearchResult? = when (item) {
        is StreamInfoItem -> videoOf(item)?.let { SearchResult.Video(it) }
        is ChannelInfoItem -> channelOf(item)?.let { SearchResult.Channel(it) }
        is PlaylistInfoItem -> playlistOf(item)?.let { SearchResult.Playlist(it) }
        else -> null
    }

    private fun filterOf(kind: SearchKind): String = when (kind) {
        SearchKind.ALL -> YoutubeSearchQueryHandlerFactory.ALL
        SearchKind.VIDEOS -> YoutubeSearchQueryHandlerFactory.VIDEOS
        SearchKind.CHANNELS -> YoutubeSearchQueryHandlerFactory.CHANNELS
        SearchKind.PLAYLISTS -> YoutubeSearchQueryHandlerFactory.PLAYLISTS
    }

    /** Just the videos of a search (the feed's topic shelves): [pages] pages at most. */
    suspend fun searchVideos(query: String, pages: Int = 1): List<VideoItem> {
        var page = search(query, SearchKind.VIDEOS)
        val out = page.items.filterIsInstance<SearchResult.Video>().map { it.video }.toMutableList()
        var left = pages - 1
        while (left-- > 0 && page.hasMore) {
            page = moreSearch(page)
            out += page.items.filterIsInstance<SearchResult.Video>().map { it.video }
        }
        return out.distinctBy { it.id }
    }

    suspend fun suggestions(query: String): List<String> {
        val q = query.trim()
        if (q.isEmpty()) return emptyList()
        return runCatching {
            io("suggestions") { service.suggestionExtractor.suggestionList(q) }
        }.getOrDefault(emptyList()).map { it.trim() }.filter { it.isNotEmpty() }.distinctBy { it.lowercase() }.take(8)
    }

    // ------------------------------------------------------------------------ video

    private class Cached(val info: StreamInfo, val at: Long)

    private val infos = object : LinkedHashMap<String, Cached>(32, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, Cached>?): Boolean = size > 24
    }

    /** One lock per video: the watch page, the player and "a seguir" opening together extract it once. */
    private val locks = java.util.concurrent.ConcurrentHashMap<String, Any>()

    /** The video's [StreamInfo], reused for [INFO_TTL_MS] (stream urls live ~6 h; the numbers change slowly). */
    private fun info(id: String, fresh: Boolean = false): StreamInfo {
        val asked = System.currentTimeMillis()
        synchronized(locks.getOrPut(id) { Any() }) {
            synchronized(infos) {
                // Fresh: only an extraction newer than this ask will do (another caller may have just made one).
                infos[id]?.takeIf { if (fresh) it.at >= asked else asked - it.at < INFO_TTL_MS }?.let { return it.info }
            }
            val info = StreamInfo.getInfo(service, watchUrl(id))
            synchronized(infos) { infos[id] = Cached(info, System.currentTimeMillis()) }
            if (locks.size > 64) locks.keys.retainAll(synchronized(infos) { infos.keys.toSet() } + id)
            return info
        }
    }

    suspend fun details(id: String): VideoDetails = io("details") {
        val info = info(id)
        val related = info.relatedItems.filterIsInstance<StreamInfoItem>().mapNotNull { videoOf(it) }
            .filter { it.id != id }.distinctBy { it.id }
        VideoDetails(
            video = VideoItem(
                id = id,
                title = info.name.orEmpty(),
                channelName = info.uploaderName.orEmpty(),
                channelUrl = info.uploaderUrl?.ifBlank { null },
                channelAvatar = avatar(info.uploaderAvatars),
                thumbnailUrl = videoThumb(id, info.thumbnails),
                durationMs = info.duration.coerceAtLeast(0) * 1000,
                views = info.viewCount,
                uploadedAt = runCatching { info.uploadDate?.instant?.toEpochMilli() }.getOrNull(),
                uploadedText = info.textualUploadDate?.ifBlank { null },
                live = info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM,
                short = false,
                verified = runCatching { info.isUploaderVerified }.getOrDefault(false),
            ),
            description = textOf(info.description),
            likes = info.likeCount,
            channelSubscribers = info.uploaderSubscriberCount,
            tags = info.tags.orEmpty().filter { it.isNotBlank() },
            category = info.category?.ifBlank { null },
            related = related,
            ageLimit = info.ageLimit,
        )
    }

    /** What YouTube suggests after [id] (the feed's main source). */
    suspend fun related(id: String): List<VideoItem> = details(id).related

    /**
     * The streams to play [id]: the best H.264 video up to [maxHeight] + the M4A audio (or a muxed
     * stream), or the HLS manifest of a live. [fresh] = the last urls were refused.
     */
    /**
     * What to play for [id]. [keep] = the stream played until now (its urls expired or were refused):
     * the same files are looked for first, so the new urls continue the old bytes exactly.
     */
    suspend fun stream(id: String, maxHeight: Int, fresh: Boolean = false, keep: TubeStream? = null): TubeStream = io("stream") {
        val info = info(id, fresh)
        val live = info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM
        val hls = info.hlsUrl?.takeIf { it.isNotBlank() }
        if (live && hls != null) return@io TubeStream(hls, null, "application/x-mpegURL", null, 0, 0, hlsUrl = hls)
        keep?.let { sameFiles(info, it) }?.let { return@io it }
        pickVideo(info, maxHeight)
            ?: hls?.let { TubeStream(it, null, "application/x-mpegURL", null, 0, 0, hlsUrl = it) }
            ?: throw OnlineException("No playable video for $id", kind = OnlineException.Kind.UNAVAILABLE)
    }

    /** [keep]'s files (same [StreamTag]s) among [info]'s streams, with fresh urls; null when one is gone. */
    private fun sameFiles(info: StreamInfo, keep: TubeStream): TubeStream? {
        if (keep.hlsUrl != null) return null
        val videoTag = keep.videoTag ?: return null
        val video = (info.videoOnlyStreams + info.videoStreams)
            .firstOrNull { it.isUrl && !it.content.isNullOrBlank() && StreamTag.of(it.content) == videoTag } ?: return null
        val audioTag = keep.audioTag
        val audio = if (keep.audioUrl == null) {
            null
        } else {
            audioTag ?: return null
            info.audioStreams.firstOrNull { it.isUrl && !it.content.isNullOrBlank() && StreamTag.of(it.content) == audioTag } ?: return null
        }
        return keep.copy(videoUrl = video.content, audioUrl = audio?.content)
    }

    private fun pickVideo(info: StreamInfo, maxHeight: Int): TubeStream? {
        fun usable(s: NpVideoStream) = s.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && s.isUrl && !s.content.isNullOrBlank()
        fun describe(s: NpVideoStream) = VideoStreams.Video(
            url = s.content,
            width = s.width,
            height = s.height.takeIf { it > 0 } ?: VideoStreams.heightOf(s.getResolution()),
            fps = s.fps,
            codec = s.codec?.ifBlank { null },
            mimeType = s.format?.mimeType ?: VideoStreams.MP4,
            bitrate = s.bitrate,
        )
        val videoOnly = info.videoOnlyStreams.filter(::usable).map(::describe)
        val muxed = info.videoStreams.filter { usable(it) && !it.isVideoOnly }.map(::describe)
        val audio = AudioStreams.pick(info.audioStreams, AudioQuality.COMPATIBLE)
        val picked = VideoStreams.pick(videoOnly, muxed, audio, maxHeight) ?: return null
        return TubeStream(picked.videoUrl, picked.audioUrl, picked.videoMimeType, picked.audioMimeType, picked.width, picked.height)
    }

    // ------------------------------------------------------------------------ comments

    private class CommentsCursor(val url: String, val page: Page)

    suspend fun comments(id: String): TubePage<CommentItem> = io("comments") {
        val info = CommentsInfo.getInfo(service, watchUrl(id))
        if (info.isCommentsDisabled) return@io TubePage(emptyList())
        TubePage(
            info.relatedItems.mapNotNull { commentOf(it, info.url) },
            info.nextPage?.let { CommentsCursor(info.url, it) },
            total = info.commentsCount.toLong().takeIf { it >= 0 } ?: -1,
        )
    }

    /** The first replies of [comment] (more with [moreComments]). */
    suspend fun replies(comment: CommentItem): TubePage<CommentItem> {
        val cursor = comment.repliesCursor as? CommentsCursor ?: return TubePage(emptyList())
        return io("replies") {
            val more = CommentsInfo.getMoreItems(service, cursor.url, cursor.page)
            TubePage(more.items.mapNotNull { commentOf(it, cursor.url) }, more.nextPage?.let { CommentsCursor(cursor.url, it) })
        }
    }

    suspend fun moreComments(page: TubePage<CommentItem>): TubePage<CommentItem> {
        val cursor = page.cursor as? CommentsCursor ?: return TubePage(emptyList())
        return io("comments more") {
            val more = CommentsInfo.getMoreItems(service, cursor.url, cursor.page)
            TubePage(more.items.mapNotNull { commentOf(it, cursor.url) }, more.nextPage?.let { CommentsCursor(cursor.url, it) })
        }
    }

    private fun commentOf(c: CommentsInfoItem, url: String): CommentItem? {
        val text = textOf(c.commentText).trim()
        if (text.isEmpty()) return null
        return CommentItem(
            id = c.commentId ?: c.url ?: text.hashCode().toString(),
            author = c.uploaderName.orEmpty().removePrefix("@").let { if (c.uploaderName?.startsWith("@") == true) "@$it" else it },
            authorAvatar = avatar(c.uploaderAvatars),
            authorUrl = c.uploaderUrl?.ifBlank { null },
            text = text,
            likes = c.likeCount.toLong(),
            published = c.textualUploadDate?.ifBlank { null },
            replies = c.replyCount.coerceAtLeast(0),
            pinned = c.isPinned,
            hearted = c.isHeartedByUploader,
            byUploader = runCatching { c.isChannelOwner }.getOrDefault(false),
            verified = runCatching { c.isUploaderVerified }.getOrDefault(false),
            repliesCursor = c.replies?.takeIf { c.replyCount != 0 }?.let { CommentsCursor(url, it) },
        )
    }

    // ------------------------------------------------------------------------ channels

    private class TabCursor(val tab: ListLinkHandler, val page: Page)

    suspend fun channel(url: String): ChannelPage = io("channel") {
        val info = ChannelInfo.getInfo(service, url)
        val channel = ChannelItem(
            url = info.url ?: url,
            name = info.name.orEmpty(),
            avatarUrl = avatar(info.avatars),
            subscribers = info.subscriberCount,
            description = info.description?.let(AutoGeneratedDescription::htmlToText)?.trim()?.ifEmpty { null },
            verified = runCatching { info.isVerified }.getOrDefault(false),
        )
        val tabs = info.tabs.mapNotNull { t ->
            val kind = when {
                ChannelTabs.VIDEOS in t.contentFilters -> ChannelTabKind.VIDEOS
                ChannelTabs.SHORTS in t.contentFilters -> ChannelTabKind.SHORTS
                ChannelTabs.LIVESTREAMS in t.contentFilters -> ChannelTabKind.LIVE
                ChannelTabs.PLAYLISTS in t.contentFilters -> ChannelTabKind.PLAYLISTS
                else -> null
            }
            kind?.let { ChannelTab(it, t) }
        }.distinctBy { it.kind }.sortedBy { it.kind.ordinal }
        val tab = (tabs.firstOrNull { it.kind == ChannelTabKind.VIDEOS } ?: tabs.firstOrNull { it.kind == ChannelTabKind.LIVE })?.handler as? ListLinkHandler
        val videos = tab?.let { t ->
            runCatching {
                val tabInfo = ChannelTabInfo.getInfo(service, t)
                tabPage(t, tabInfo.relatedItems, tabInfo.nextPage, channel)
            }.getOrNull()
        } ?: TubePage(emptyList())
        ChannelPage(channel, info.banners.maxByOrNull { it.width }?.url, videos, tabs)
    }

    /** The first page of one of a channel's tabs (videos, shorts, lives as videos; playlists as playlists). */
    suspend fun channelTab(tab: ChannelTab, channel: ChannelItem): TubePage<SearchResult> = io("channel tab") {
        val handler = tab.handler as ListLinkHandler
        val info = ChannelTabInfo.getInfo(service, handler)
        tabResults(handler, info.relatedItems, info.nextPage, channel)
    }

    suspend fun moreChannelTab(page: TubePage<SearchResult>, channel: ChannelItem): TubePage<SearchResult> {
        val cursor = page.cursor as? TabCursor ?: return TubePage(emptyList())
        return io("channel tab more") {
            val more = ChannelTabInfo.getMoreItems(service, cursor.tab, cursor.page)
            tabResults(cursor.tab, more.items, more.nextPage, channel)
        }
    }

    private fun tabResults(tab: ListLinkHandler, items: List<InfoItem>, next: Page?, channel: ChannelItem): TubePage<SearchResult> {
        val results = items.mapNotNull { item ->
            when (item) {
                is StreamInfoItem -> videoOf(item)?.let {
                    SearchResult.Video(
                        it.copy(
                            channelName = it.channelName.ifBlank { channel.name },
                            channelUrl = it.channelUrl ?: channel.url,
                            channelAvatar = it.channelAvatar ?: channel.avatarUrl,
                        ),
                    )
                }
                is PlaylistInfoItem -> playlistOf(item)?.let { SearchResult.Playlist(it.copy(uploader = it.uploader ?: channel.name)) }
                else -> null
            }
        }
        return TubePage(results, next?.let { TabCursor(tab, it) })
    }

    suspend fun moreChannelVideos(page: TubePage<VideoItem>, channel: ChannelItem): TubePage<VideoItem> {
        val cursor = page.cursor as? TabCursor ?: return TubePage(emptyList())
        return io("channel more") {
            val more = ChannelTabInfo.getMoreItems(service, cursor.tab, cursor.page)
            tabPage(cursor.tab, more.items, more.nextPage, channel)
        }
    }

    private fun tabPage(tab: ListLinkHandler, items: List<InfoItem>, next: Page?, channel: ChannelItem): TubePage<VideoItem> {
        val videos = items.filterIsInstance<StreamInfoItem>().mapNotNull { videoOf(it) }.map {
            // Tab rows don't repeat the channel: fill it in.
            it.copy(
                channelName = it.channelName.ifBlank { channel.name },
                channelUrl = it.channelUrl ?: channel.url,
                channelAvatar = it.channelAvatar ?: channel.avatarUrl,
            )
        }
        return TubePage(videos, next?.let { TabCursor(tab, it) })
    }

    /**
     * A channel's latest uploads, light: its RSS feed (one small request, ~15 videos with dates and
     * views, no lengths). When the feed can't be read, the first page of its videos tab.
     */
    suspend fun latest(channelUrl: String, name: String? = null, avatar: String? = null): List<VideoItem> {
        val fromFeed = runCatching {
            io("feed") {
                val extractor = service.getFeedExtractor(channelUrl) ?: return@io emptyList()
                extractor.fetchPage()
                extractor.initialPage.items.filterIsInstance<StreamInfoItem>().mapNotNull { videoOf(it) }
            }
        }.getOrNull().orEmpty()
        val list = fromFeed.ifEmpty { runCatching { channel(channelUrl).videos.items }.getOrDefault(emptyList()) }
        return list.map {
            it.copy(
                channelName = it.channelName.ifBlank { name.orEmpty() },
                channelUrl = it.channelUrl ?: channelUrl,
                channelAvatar = it.channelAvatar ?: avatar,
            )
        }
    }

